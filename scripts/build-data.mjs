import { readFileSync, writeFileSync, existsSync } from 'node:fs'

const readJson = (url) => {
  const raw = readFileSync(url, 'utf8')
  return JSON.parse(raw.charCodeAt(0) === 0xfeff ? raw.slice(1) : raw)
}

const posts = readJson(new URL('../.data/posts.json', import.meta.url))
const manifestPath = new URL('../media-manifest.json', import.meta.url)
const manifest = existsSync(manifestPath) ? readJson(manifestPath) : []
const mediaById = new Map(manifest.map((m) => [m.id, m]))

const stripLinks = (t) =>
  t
    .split('\n')
    .map((line) => line.replace(/https:\/\/t\.co\/\S+/g, '').trimEnd())
    .join('\n')
    .replace(/\n{3,}/g, '\n\n')
    .trim()

const CATEGORY_RULES = [
  ['listings', /\b(listed|listing|verified for trading|audit|audited|go[sS]plus|coinmarketcap|cmc\b|coingecko|bitget|gate\b|okx|ave dex|gems radar|bullx|ctotrends)/i],
  ['trending', /(trending|dexs? trends?|boost|volume|ath\b|chart|climbing|swapped|dex)/i],
  ['community', /(community|members?|holders?|holding|chat|feedback|together|guys|discord|supporters|milestone of the first 1000)/i],
  ['marketing', /(marketing|ads?\b|influencer|conference|nvidia|gtc|promo|promotion|show|partnership)/i],
  ['product', /(feature|ai (is|model|software|tool)|website|launch|release|live|transform|animate|video|image|generate|creator|imagine|upload|cartoon style)/i],
]

function classify(text) {
  for (const [cat, re] of CATEGORY_RULES) if (re.test(text)) return cat
  return 'product'
}

// Media kept out of the gallery on request. Posts stay in the archive; only the
// artwork is withheld, and it can never be pulled back in by re-running `npm run data`.
const EXCLUDED_MEDIA = new Set([
  '1892748455820275867',
  '1892746038563205551',
  '1892729761308274720',
  '1892725337701646352',
  '1892721204261228991',
  '1892627275553579236',
  '1892665618895151306',
  '1892679253382017239',
  '1892596096058216629',
  '1892434738851328391',
  '1892293456703172942',
  '1892104478800687454',
])

const gallery = []
const renderedPosts = posts.map((p) => {
  const display = stripLinks(p.text)
  const m = mediaById.get(p.id)
  if (m && !EXCLUDED_MEDIA.has(String(p.id))) {
    gallery.push({
      id: p.id,
      dateLabel: p.dateLabel,
      created: p.created,
      caption: display,
      category: classify(p.text),
      kind: m.kind,
      src: m.file,
      thumb: m.thumb,
      link: p.link,
      likes: p.likes,
      replies: p.replies,
    })
  }
  return {
    id: p.id,
    created: p.created,
    dateLabel: p.dateLabel,
    text: display,
    link: p.link,
    likes: p.likes,
    rts: p.rts,
    replies: p.replies,
    hasMedia: p.media.length > 0,
    category: classify(p.text),
  }
})

const counts = {}
for (const g of gallery) counts[g.category] = (counts[g.category] || 0) + 1

const now = new Date().toISOString().slice(0, 10)

const ts = `/* eslint-disable */
// AUTO-GENERATED by scripts/build-data.mjs -- do not edit by hand.
// Source: public timeline archive of X account @CARTOON_SOL (syndication endpoint),
// fetched ${now}. Text is the account's own wording; trailing t.co media links removed for display.

export type GalleryCategory =
  | 'product'
  | 'trending'
  | 'community'
  | 'listings'
  | 'marketing'

export interface Post {
  id: string
  created: string
  dateLabel: string
  text: string
  link: string
  likes: number
  rts: number
  replies: number
  hasMedia: boolean
  category: GalleryCategory
}

export interface GalleryItem {
  id: string
  dateLabel: string
  created: string
  caption: string
  category: GalleryCategory
  kind: 'photo' | 'video'
  src: string
  thumb: string
  link: string
  likes: number
  replies: number
}

export const ARCHIVE_DATE = ${JSON.stringify(now)}
export const POSTS: Post[] = ${JSON.stringify(renderedPosts, null, 2)}
export const GALLERY: GalleryItem[] = ${JSON.stringify(gallery, null, 2)}
`

writeFileSync(new URL('../src/data/content.ts', import.meta.url), ts, 'utf8')
console.log('posts:', renderedPosts.length, 'gallery:', gallery.length, 'categories:', counts, 'archive:', now)
